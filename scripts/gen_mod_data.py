#!/usr/bin/env python3
"""Data compiled into the mod.

  gen_mod_data.py cs <padmap.txt> <out ModData.cs>
  gen_mod_data.py words <pt-BR.json> <out words.txt>

ModData.Words is compiled as a placeholder: the dictionary holds the game's own English text, so
it is never part of the mod's build output. At patch time, PatchAssemblies writes the dictionary
rebuilt from the user's APK (the `words` file) into RavenMod.dll in its place.
"""
import json
import sys

WORDS_PLACEHOLDER = "@@RAVENMOD_WORDS@@"


def literal(s):
    out = []
    for ch in s:
        c = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif c < 0x20 or c > 0x7e:
            out.append("\\u%04x" % c)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def cs(padmap, dst):
    pad = []
    with open(padmap, encoding="utf-8") as fh:
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 4:
                pad.append("\x01".join((parts[0], parts[2], parts[3])))
    with open(dst, "w", encoding="ascii") as fh:
        fh.write("// Generated by scripts/gen_mod_data.py. Do not edit.\n")
        fh.write("public static class ModData\n{\n")
        fh.write("    public const string Words = " + literal(WORDS_PLACEHOLDER) + ";\n")
        fh.write("    public const string Pad = " + literal("\x01".join(pad)) + ";\n}\n")
    print(f"{len(pad)} gamepad bindings")


def words(src, dst):
    with open(src, encoding="utf-8") as fh:
        table = json.load(fh)
    with open(dst, "w", encoding="utf-8", newline="") as fh:
        fh.write("\x01".join(k + "\x01" + v for k, v in sorted(table.items())))
    print(f"{len(table)} translations")


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "cs":
        cs(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 4 and sys.argv[1] == "words":
        words(sys.argv[2], sys.argv[3])
    else:
        raise SystemExit(__doc__)
